def get_port_info(port):
    if port in COMMON_PORTS:
        return COMMON_PORTS[port]

    if 0 <= port <= 1023:
        return "Well-known (unknown service)"
    elif 1024 <= port <= 49151:
        return "Registered (unknown service)"
    elif 49152 <= port <= 65535:
        return "Ephemeral"
    else:
        return "Invalid"